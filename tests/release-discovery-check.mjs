import fs from 'node:fs';
import assert from 'node:assert/strict';
import {searchHelp} from '../src/components/seo-drafts/help-search.mjs';
const read = name => JSON.parse(fs.readFileSync(`src/content/seo-drafts/${name}.json`, 'utf8'));
const final = read('acquisition-final');
assert.deepEqual(read('acquisition-final-summaries'), final.map(({body,...summary})=>summary));
assert.ok(read('acquisition-final-summaries').every(r=>!('body' in r)), 'No complete article prose sent to the client index');
const fixture = {title:'Example',intro:'Introduction',category:'Stock',steps:['Step'],success:'The adjustment reference appears.',troubleshoot:'Contact support'};
assert.equal(searchHelp([fixture],'adjustment reference').length,1,'Search includes the expected result');
assert.equal(searchHelp([fixture],'adjustment reference','Other').length,0,'Category remains scoped');
const out = process.env.EDITORIAL_OUT;
assert.ok(out, 'Set EDITORIAL_OUT');
const files=[`${out}/blog/index.html`,...fs.readdirSync(`${out}/blog/page`).sort((a,b)=>Number(a)-Number(b)).map(n=>`${out}/blog/page/${n}/index.html`)];
const pages=files.map(file=>fs.readFileSync(file,'utf8'));
pages.forEach((html,i)=>{
 assert.equal((html.match(/<main\b/g)||[]).length,1,'One main landmark per library page');
 const count=(html.match(/<h2\b/g)||[]).length;
 assert.ok(count>0&&count<=24,'At most 24 article cards per page');
 const route=i===0?'/blog/':`/blog/page/${i+1}/`;
 assert.ok(html.includes(`href="https://www.obizee.com${route}"`)||i===0&&html.includes('href="https://www.obizee.com/blog"'),'Self canonical');
 if(i>0)assert.ok(html.includes('rel="prev"'),'Previous link');
 if(i<pages.length-1)assert.ok(html.includes('rel="next"'),'Next link');
});
const html=pages.join('\n');
const routes=[...read('articles'),...final].filter(r=>r.route.startsWith('/blog/')).map(r=>r.route);
const links=new Set([...html.matchAll(/href="([^"?#]+)(?:[?#][^"]*)?"/g)].map(m=>m[1].replace(/\/$/,'')));
const missing=routes.filter(r=>!links.has(r.replace(/\/$/,'')));
console.log(JSON.stringify({libraryPages:pages.length,blogArticles:routes.length,missingCount:missing.length,missing},null,2));
assert.equal(missing.length,0,'All programme blog articles appear on the actual /blog/ route, not only editorial-preview');
